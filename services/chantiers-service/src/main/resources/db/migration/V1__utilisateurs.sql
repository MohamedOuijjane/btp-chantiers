-- Schéma auth (ADR-0006) : comptes de connexion. Le mot de passe est haché avec BCrypt ;
-- NULL = aucun mot de passe défini, la connexion est refusée.
CREATE TABLE utilisateurs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(254) NOT NULL UNIQUE,
    mot_de_passe VARCHAR(100),
    nom          VARCHAR(150) NOT NULL,
    initiales    VARCHAR(4)   NOT NULL,
    role         VARCHAR(20)  NOT NULL
        CHECK (role IN ('DIRECTION', 'CONDUCTEUR', 'CHEF_CHANTIER', 'MAGASINIER')),
    -- Compte de démonstration : son mot de passe suit la variable DEMO_MOT_DE_PASSE.
    demo         BOOLEAN      NOT NULL DEFAULT FALSE,
    cree_le      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
